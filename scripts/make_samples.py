"""데모/테스트용 샘플 엑셀 생성: python scripts/make_samples.py [출력폴더]

운행일지·계근표에 정상 건과 함께 다음 오류를 의도적으로 포함한다.
  - 수량 불일치 (10/13 경기12가3456 한국가스산업)
  - 계근표 누락  (10/13 서울80바1234 대한LPG)
  - 중복 기록    (10/14 경기12가3456 한국가스산업, 운행일지 2건 동일)
  - 거래처 미매칭 (10/14 인천34나5678 '코리아에너지')
  - 인식 불확실  (계근표 총중량-공차≠순중량)
"""
import sys
from pathlib import Path

from openpyxl import Workbook

OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent / "sample_data"
OUT.mkdir(parents=True, exist_ok=True)


def write(name, headers, rows):
    wb = Workbook()
    ws = wb.active
    ws.append(headers)
    for r in rows:
        ws.append(list(r))
    wb.save(OUT / name)


write("customers.xlsx", ["거래처코드", "거래처명", "별칭"], [
    ("C001", "한국가스산업", "한국가스,(주)한국가스산업"),
    ("C002", "대한LPG", "대한엘피지"),
    ("C003", "서해에너지", ""),
])
write("items.xlsx", ["품목명", "단위", "별칭"], [
    ("프로판", "kg", "LPG프로판,propane"),
    ("부탄", "kg", "LPG부탄"),
])

LOG_H = ["일자", "차량번호", "거래처", "사업장", "품목", "수량", "단위"]
WEIGH_H = ["계근일자", "차량번호", "거래처", "품목", "총중량", "공차중량", "순중량", "단위"]

write("운행일지_샘플.xlsx", LOG_H, [
    ("2026-10-13", "경기12가3456", "한국가스산업", "평택공장", "프로판", 12000, "kg"),
    ("2026-10-13", "경기12가3456", "서해에너지", "당진센터", "부탄", 8000, "kg"),
    ("2026-10-13", "서울80바1234", "대한LPG", "인천저장소", "프로판", 15000, "kg"),
    ("2026-10-14", "경기12가3456", "한국가스산업", "평택공장", "프로판", 11000, "kg"),
    ("2026-10-14", "경기12가3456", "한국가스산업", "평택공장", "프로판", 11000, "kg"),
    ("2026-10-14", "인천34나5678", "코리아에너지", "송도", "부탄", 9000, "kg"),
    ("2026-10-15", "경기12가3456", "대한엘피지", "인천저장소", "LPG프로판", 9000, "kg"),
])
write("계근표_샘플.xlsx", WEIGH_H, [
    ("2026-10-13", "경기 12가 3456", "한국가스산업", "프로판", 22000, 10000, 11800, "kg"),   # 수량 불일치(12000 vs 11800)
    ("2026-10-13", "경기12가3456", "서해에너지", "부탄", 18000, 10000, 8000, "kg"),
    ("2026-10-14", "경기12가3456", "한국가스산업", "프로판", 21000, 10000, 11000, "kg"),
    ("2026-10-14", "경기12가3456", "한국가스산업", "프로판", 21000, 10000, 11000, "kg"),
    ("2026-10-14", "인천34나5678", "코리아에너지", "부탄", 19000, 10000, 9000, "kg"),
    ("2026-10-15", "경기12가3456", "대한LPG", "프로판", 17000, 10000, 9000, "kg"),          # 총-공차≠순
])
print("생성 위치:", OUT)
